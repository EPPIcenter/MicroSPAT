//! TypeScript generation: `ui/src/api/bindings/*.ts` (one file per type,
//! from `ts_rs`) and `ui/src/api/client.ts` (one typed function per method,
//! from the registry). Method names and types therefore cannot drift from
//! the engine. Regenerate with
//!
//! ```sh
//! cargo run -p microspat-engine --bin gen-bindings
//! ```
//!
//! and a test (`tests/bindings.rs`) fails when the checked-in files are stale.
//! 64-bit integers (ids) are emitted as `number`: ids are SQLite rowids, far
//! below 2^53.

use crate::events::{AppEvent, TaskInfo};
use crate::rpc::MethodKind;
use crate::{Engine, EngineConfig, RpcError};
use microspat_core::peaks::FilterParams;
use microspat_core::{Bin, LocusInfo, Peak};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use ts_rs::{Config, TS};

const HEADER: &str =
    "// Generated by `cargo run -p microspat-engine --bin gen-bindings`. Do not edit.\n";

/// Default output directory: `ui/src/api` of this repository.
pub fn default_out_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ui/src/api")
}

/// Writes `bindings/` and `client.ts` into `api_dir`, replacing the old ones.
pub fn generate(api_dir: &Path) -> Result<(), String> {
    let bindings = api_dir.join("bindings");
    if bindings.exists() {
        std::fs::remove_dir_all(&bindings).map_err(|e| format!("{}: {e}", bindings.display()))?;
    }
    std::fs::create_dir_all(&bindings).map_err(|e| format!("{}: {e}", bindings.display()))?;
    let cfg = Config::new()
        .with_large_int("number")
        .with_out_dir(&bindings);
    let engine = Engine::new(EngineConfig::default());
    for m in engine.registry().infos() {
        m.export_types(&cfg)
            .map_err(|e| format!("{}: {e}", m.name))?;
    }
    // The event and error contract (transport.ts) and the shared analysis
    // types of microspat-core that UI components use before any method returns them.
    for r in [
        AppEvent::export_all(&cfg),
        TaskInfo::export_all(&cfg),
        RpcError::export_all(&cfg),
        Peak::export_all(&cfg),
        Bin::export_all(&cfg),
        LocusInfo::export_all(&cfg),
        FilterParams::export_all(&cfg),
    ] {
        r.map_err(|e| e.to_string())?;
    }

    let mut names: Vec<String> = std::fs::read_dir(&bindings)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok())
        .filter_map(|e| {
            e.file_name()
                .to_str()?
                .strip_suffix(".ts")
                .map(str::to_string)
        })
        .collect();
    names.sort();
    let mut index = String::from(HEADER);
    for n in &names {
        let _ = writeln!(index, "export type {{ {n} }} from './{n}'");
    }
    write(&bindings.join("index.ts"), &index)?;
    write(&api_dir.join("client.ts"), &client(&engine, &cfg, &names))?;
    Ok(())
}

fn write(path: &Path, content: &str) -> Result<(), String> {
    std::fs::write(path, content).map_err(|e| format!("{}: {e}", path.display()))
}

fn identifiers(ts: &str) -> impl Iterator<Item = &str> {
    ts.split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
        .filter(|s| !s.is_empty())
}

fn doc_comment(out: &mut String, indent: &str, text: &str) {
    let _ = writeln!(out, "{indent}/** {} */", text.replace("*/", "* /"));
}

fn client(engine: &Engine, cfg: &Config, type_names: &[String]) -> String {
    let known: BTreeSet<&str> = type_names.iter().map(String::as_str).collect();
    let methods: Vec<_> = engine.registry().infos().collect();
    let mut used = BTreeSet::new();
    for m in &methods {
        for t in [m.params_type(cfg), m.result_type(cfg)] {
            for id in identifiers(&t) {
                if known.contains(id) {
                    used.insert(id.to_string());
                }
            }
        }
    }
    let mut out = String::from(HEADER);
    out.push_str(
        "/**\n * Typed engine client: one function per RPC method. Built from the engine's\n",
    );
    out.push_str(" * method registry, so names and types match the engine exactly.\n */\n");
    out.push_str("import { rpc } from './transport'\n");
    let used: Vec<String> = used.into_iter().collect();
    let _ = writeln!(
        out,
        "import type {{ {} }} from './bindings'\n",
        used.join(", ")
    );

    out.push_str("/** Params and result type of every method. */\nexport interface Methods {\n");
    for m in &methods {
        let _ = writeln!(
            out,
            "  {}: {{ params: {}; result: {} }}",
            m.name,
            m.params_type(cfg),
            m.result_type(cfg)
        );
    }
    out.push_str("}\n\nexport type MethodName = keyof Methods\n\n");

    out.push_str(
        "/** Entities each method may announce in `changed` events (query-key prefixes). */\n",
    );
    out.push_str("export const METHOD_CHANGES = {\n");
    for m in &methods {
        let list: Vec<String> = m.changes.iter().map(|c| format!("'{c}'")).collect();
        let _ = writeln!(out, "  {}: [{}],", m.name, list.join(", "));
    }
    out.push_str("} as const satisfies Record<MethodName, readonly string[]>\n\n");

    out.push_str(
        "/** Methods that run as background tasks (progress arrives as `task` events). */\n",
    );
    let tasks: Vec<String> = methods
        .iter()
        .filter(|m| m.kind == MethodKind::Task)
        .map(|m| format!("'{}'", m.name))
        .collect();
    let _ = writeln!(
        out,
        "export const TASK_METHODS: readonly MethodName[] = [{}]\n",
        tasks.join(", ")
    );

    out.push_str("/** Call a method by name with typed params and result. */\n");
    out.push_str("export function call<M extends MethodName>(method: M, params: Methods[M]['params']): Promise<Methods[M]['result']> {\n");
    out.push_str("  return rpc<Methods[M]['result']>(method, params)\n}\n\n");

    out.push_str("export const api = {\n");
    for m in &methods {
        let mut doc = m.doc.to_string();
        if !m.changes.is_empty() {
            let _ = write!(doc, " Changes: {}.", m.changes.join(", "));
        }
        if m.kind == MethodKind::Task {
            doc.push_str(" Background task.");
        }
        doc_comment(&mut out, "  ", &doc);
        let params = m.params_type(cfg);
        let result = m.result_type(cfg);
        if params == "null" {
            let _ = writeln!(
                out,
                "  {}: (): Promise<{result}> => rpc<{result}>('{}'),",
                m.name, m.name
            );
        } else {
            let _ = writeln!(
                out,
                "  {}: (params: {params}): Promise<{result}> => rpc<{result}>('{}', params),",
                m.name, m.name
            );
        }
    }
    out.push_str("} as const\n");
    out
}
